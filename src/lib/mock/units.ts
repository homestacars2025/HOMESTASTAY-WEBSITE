function gallery(unitId: string, coverUrl: string, offset = 0): UnitMediaItem[] {
  return [
    {
      id:         `media-${unitId}-0`,
      unit_id:    unitId,
      media_type: 'image',
      file_path:  `units/${unitId}/cover.jpg`,
      public_url: coverUrl,
      is_cover:   true,
      sort_order: 0,
    },
    ...Array.from({ length: 4 }, (_, i) => ({
      id:         `media-${unitId}-${i + 1}`,
      unit_id:    unitId,
      media_type: 'image',
      file_path:  `units/${unitId}/gallery-${i + 1}.jpg`,
      public_url: GALLERY_POOL[(offset + i) % GALLERY_POOL.length],
      is_cover:   false,
      sort_order: i + 1,
    })),
  ];
}

